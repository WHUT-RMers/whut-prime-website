class Command(BaseCommand):
    help = '导入或更新 6 篇 PRIME 官网长文演示资讯及轮播图片；按 slug 幂等执行。'

    def handle(self, *args, **options):
        now = timezone.now()
        for item in DEMO_ARTICLES:
            defaults = {
                'title': item['title'], 'summary': item['summary'], 'category': item['category'], 'body': item['body'],
                'status': NewsArticle.Status.PUBLISHED, 'published_at': now - timedelta(days=item['days_ago']),
                'is_featured': item['featured'], 'is_pinned': item['pinned'], 'cover_caption': item['captions'][0],
            }
            article, created = NewsArticle.objects.update_or_create(slug=item['slug'], defaults=defaults)
            if created or not article.cover:
                with (ASSET_DIR / item['cover']).open('rb') as image:
                    article.cover.save(item['cover'], File(image), save=True)
            if created:
                for position, (filename, caption) in enumerate(zip(item['slides'], item['captions']), start=1):
                    slide = NewsCoverSlide(article=article, caption=caption, sort_order=position)
                    with (ASSET_DIR / filename).open('rb') as image:
                        slide.image.save(filename, File(image), save=True)
            self.stdout.write(self.style.SUCCESS(f'已更新：{article.title}'))
